<?php

declare(strict_types=1);

use Illuminate\Contracts\Console\Kernel;
use Illuminate\Foundation\Vite;
use Illuminate\Support\Facades\URL;

$projectRoot = dirname(__DIR__);
$outputPath = $projectRoot.DIRECTORY_SEPARATOR.'dist';
$manifestPath = $projectRoot.DIRECTORY_SEPARATOR.'storage'.DIRECTORY_SEPARATOR.'app'.DIRECTORY_SEPARATOR.'static-site-manifest.json';
$viteManifestPath = $projectRoot.DIRECTORY_SEPARATOR.'public'.DIRECTORY_SEPARATOR.'build'.DIRECTORY_SEPARATOR.'manifest.json';

if (! is_file($viteManifestPath)) {
    fwrite(STDERR, "Vite production assets are missing. Run the static build command again.\n");
    exit(1);
}

require $projectRoot.DIRECTORY_SEPARATOR.'vendor'.DIRECTORY_SEPARATOR.'autoload.php';
$app = require $projectRoot.DIRECTORY_SEPARATOR.'bootstrap'.DIRECTORY_SEPARATOR.'app.php';
$app->make(Kernel::class)->bootstrap();

URL::forceRootUrl('.');
app(Vite::class)->createAssetPathsUsing(
    fn (string $path): string => './'.ltrim($path, '/'),
);

$html = view('welcome')->render();
$html = str_replace(
    ['url("./instrument-sans-', "url('./instrument-sans-"],
    ['url("./build/assets/instrument-sans-', "url('./build/assets/instrument-sans-"],
    $html,
);

function listStaticFiles(string $directory): array
{
    $files = [];

    if (! is_dir($directory)) {
        return $files;
    }

    $iterator = new RecursiveIteratorIterator(
        new RecursiveDirectoryIterator($directory, FilesystemIterator::SKIP_DOTS),
    );

    foreach ($iterator as $file) {
        if ($file->isLink()) {
            throw new RuntimeException('Static output does not accept symbolic links.');
        }

        if ($file->isFile()) {
            $files[] = str_replace(DIRECTORY_SEPARATOR, '/', substr($file->getPathname(), strlen($directory) + 1));
        }
    }

    sort($files);

    return $files;
}

function removeGeneratedOutput(string $outputPath, string $manifestPath): void
{
    if (! file_exists($outputPath)) {
        return;
    }

    if (is_link($outputPath) || ! is_dir($outputPath)) {
        throw new RuntimeException('The dist path exists and is not a normal directory; leaving it untouched.');
    }

    if (! is_file($manifestPath)) {
        if (scandir($outputPath) === ['.', '..']) {
            rmdir($outputPath);

            return;
        }

        throw new RuntimeException('dist already exists and is not marked as generated by this exporter; leaving it untouched.');
    }

    $manifest = json_decode((string) file_get_contents($manifestPath), true);

    if (! is_array($manifest) || ! isset($manifest['files']) || ! is_array($manifest['files'])) {
        throw new RuntimeException('The static output manifest is invalid; leaving dist untouched.');
    }

    $actualFiles = listStaticFiles($outputPath);
    $unexpectedFiles = array_values(array_diff($actualFiles, $manifest['files']));

    if ($unexpectedFiles !== []) {
        throw new RuntimeException('dist contains files not created by this exporter; leaving the directory untouched.');
    }

    foreach ($actualFiles as $relativePath) {
        $path = $outputPath.DIRECTORY_SEPARATOR.str_replace('/', DIRECTORY_SEPARATOR, $relativePath);

        if (! is_file($path) || is_link($path)) {
            throw new RuntimeException('The previous static output contains a non-file path; leaving dist untouched.');
        }

        unlink($path);
    }

    $directories = [];
    $iterator = new RecursiveIteratorIterator(
        new RecursiveDirectoryIterator($outputPath, FilesystemIterator::SKIP_DOTS),
        RecursiveIteratorIterator::CHILD_FIRST,
    );

    foreach ($iterator as $entry) {
        if ($entry->isLink()) {
            throw new RuntimeException('The previous static output contains a symbolic link; leaving dist untouched.');
        }

        if ($entry->isDir()) {
            $directories[] = $entry->getPathname();
        }
    }

    foreach ($directories as $directory) {
        rmdir($directory);
    }

    rmdir($outputPath);
}

function ensureDirectory(string $path): void
{
    if (! is_dir($path) && ! mkdir($path, 0777, true) && ! is_dir($path)) {
        throw new RuntimeException("Could not create static output directory: {$path}");
    }
}

function copyProductionAssets(string $source, string $destination): void
{
    $allowedExtensions = ['css', 'js', 'woff', 'woff2', 'ttf', 'otf', 'svg', 'png', 'jpg', 'jpeg', 'webp', 'avif', 'gif'];
    $iterator = new RecursiveIteratorIterator(
        new RecursiveDirectoryIterator($source, FilesystemIterator::SKIP_DOTS),
    );

    foreach ($iterator as $file) {
        if ($file->isLink()) {
            throw new RuntimeException('Vite build assets must not contain symbolic links.');
        }

        if (! $file->isFile() || ! in_array(strtolower($file->getExtension()), $allowedExtensions, true)) {
            continue;
        }

        $relativePath = substr($file->getPathname(), strlen($source) + 1);
        $target = $destination.DIRECTORY_SEPARATOR.$relativePath;
        ensureDirectory(dirname($target));

        if (! copy($file->getPathname(), $target)) {
            throw new RuntimeException("Could not copy Vite asset: {$relativePath}");
        }
    }
}

function copyPublicImages(string $source, string $destination): void
{
    $allowedExtensions = ['png', 'jpg', 'jpeg', 'webp', 'avif', 'gif', 'svg'];

    if (! is_dir($source)) {
        return;
    }

    $iterator = new RecursiveIteratorIterator(
        new RecursiveDirectoryIterator($source, FilesystemIterator::SKIP_DOTS),
    );

    foreach ($iterator as $file) {
        if ($file->isLink()) {
            throw new RuntimeException('Public images must not contain symbolic links.');
        }

        if (! $file->isFile() || ! in_array(strtolower($file->getExtension()), $allowedExtensions, true)) {
            continue;
        }

        $relativePath = substr($file->getPathname(), strlen($source) + 1);
        $target = $destination.DIRECTORY_SEPARATOR.$relativePath;
        ensureDirectory(dirname($target));

        if (! copy($file->getPathname(), $target)) {
            throw new RuntimeException("Could not copy public image: {$relativePath}");
        }
    }
}

function removeTree(string $path): void
{
    if (! is_dir($path) || is_link($path)) {
        return;
    }

    $iterator = new RecursiveIteratorIterator(
        new RecursiveDirectoryIterator($path, FilesystemIterator::SKIP_DOTS),
        RecursiveIteratorIterator::CHILD_FIRST,
    );

    foreach ($iterator as $entry) {
        if ($entry->isLink() || $entry->isFile()) {
            unlink($entry->getPathname());
        } elseif ($entry->isDir()) {
            rmdir($entry->getPathname());
        }
    }

    rmdir($path);
}

$stagePath = $projectRoot.DIRECTORY_SEPARATOR.'.static-stage-'.bin2hex(random_bytes(8));

try {
    ensureDirectory($stagePath);
    file_put_contents($stagePath.DIRECTORY_SEPARATOR.'index.html', $html);

    copyProductionAssets(
        $projectRoot.DIRECTORY_SEPARATOR.'public'.DIRECTORY_SEPARATOR.'build'.DIRECTORY_SEPARATOR.'assets',
        $stagePath.DIRECTORY_SEPARATOR.'build'.DIRECTORY_SEPARATOR.'assets',
    );
    copyPublicImages(
        $projectRoot.DIRECTORY_SEPARATOR.'public'.DIRECTORY_SEPARATOR.'images',
        $stagePath.DIRECTORY_SEPARATOR.'images',
    );

    foreach (['favicon.ico', 'robots.txt'] as $publicFile) {
        $source = $projectRoot.DIRECTORY_SEPARATOR.'public'.DIRECTORY_SEPARATOR.$publicFile;

        if (is_file($source)) {
            copy($source, $stagePath.DIRECTORY_SEPARATOR.$publicFile);
        }
    }

    file_put_contents($stagePath.DIRECTORY_SEPARATOR.'.nojekyll', '');
    $files = listStaticFiles($stagePath);
    $manifestContents = json_encode(['files' => $files], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR);

    removeGeneratedOutput($outputPath, $manifestPath);

    if (! rename($stagePath, $outputPath)) {
        throw new RuntimeException('Could not move the generated static site into dist.');
    }

    ensureDirectory(dirname($manifestPath));
    file_put_contents($manifestPath, $manifestContents);
    fwrite(STDOUT, 'Static site written to dist/ with '.count($files)." files.\n");
} catch (Throwable $exception) {
    removeTree($stagePath);
    fwrite(STDERR, $exception->getMessage()."\n");
    exit(1);
}
